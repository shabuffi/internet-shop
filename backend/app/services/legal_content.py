# Реестр редактируемых инфо-страниц: slug → (заголовок, ключ настройки, тело по умолчанию).
INFO_PAGES = {
    "order":   {"title": "Оформление заказа", "key": "order_info_body", "default": DEFAULT_ORDER_INFO_BODY},
    "payment": {"title": "Оплата",            "key": "payment_body",     "default": DEFAULT_PAYMENT_BODY},
}


def _get(db: Session, key: str, default: str = "") -> str:
    row = db.get(ShopSettings, key)
    return row.value if row and row.value else default


def get_info_pages(db: Session) -> dict:
    """Инфо-страницы (тело + заголовок) по slug — для витрины и редактора админки."""
    return {
        slug: {"title": p["title"], "body": _get(db, p["key"], p["default"])}
        for slug, p in INFO_PAGES.items()
    }


def get_privacy(db: Session) -> dict:
    """Текущая политика: тело, дата редакции и реквизиты оператора.

    Структуру разделяют публичный эндпоинт витрины и админка (редактор + превью).
    """
    return {
        "body": _get(db, "privacy_body", DEFAULT_PRIVACY_BODY),
        "revision": _get(db, "privacy_revision", ""),
        "operator": {field: _get(db, key) for field, key in OPERATOR_KEYS.items()},
    }
