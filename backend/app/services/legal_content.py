"""Контент юридических страниц (политика обработки ПД), редактируемый в админке.

Хранится в key-value таблице ``ShopSettings``:
  • ``privacy_body``     — тело политики (markdown-lite с плейсхолдерами ``{{...}}``);
  • ``privacy_revision`` — дата редакции (строка, показывается под заголовком).

Реквизиты оператора берутся из тех же ключей настроек магазина, что и страницы
«О компании»/«Контакты» (``company_legal_name`` и т.п.) — правятся на странице
политики и подставляются в плейсхолдеры на витрине и в превью админки.
"""

from sqlalchemy.orm import Session

from app.db.models.admin import ShopSettings

# Соответствие «поле оператора → ключ настройки магазина».
OPERATOR_KEYS = {
    "name": "company_legal_name",
    "inn": "company_inn",
    "ogrn": "company_ogrn",
    "address": "warehouse_address",
    "email": "contact_email",
    "phone": "contact_phone",
}

# Шаблон политики по умолчанию (если в БД ещё ничего не сохранено). Плейсхолдеры
# ``{{...}}`` подставляются на фронте из реквизитов оператора. Это рыба — подлежит
# вычитке юристом; редактируется в админке без правки кода.
DEFAULT_PRIVACY_BODY = """## 1. Общие положения
Настоящая Политика определяет порядок обработки и защиты персональных данных физических лиц (далее — Пользователи), пользующихся сайтом и услугами {{наименование}} (далее — Оператор). Политика разработана в соответствии с Федеральным законом от 27.07.2006 № 152-ФЗ «О персональных данных».

## 2. Оператор
Оператор: {{наименование}}, ИНН {{инн}}, ОГРН {{огрн}}, адрес: {{адрес}}, электронная почта: {{email}}, телефон: {{телефон}}.

## 3. Какие данные обрабатываются
При регистрации и оформлении заказа Оператор обрабатывает: адрес электронной почты, номер телефона, наименование заказчика (ФИО для физического лица; наименование и ИНН для ИП и ООО), а также сведения о заказах. Специальные категории персональных данных не обрабатываются.

## 4. Цели обработки
Регистрация и ведение личного кабинета; оформление, исполнение и доставка заказов; связь с Пользователем по поводу заказов; выполнение требований законодательства РФ.

## 5. Правовые основания
Согласие Пользователя на обработку персональных данных; договор, стороной которого является Пользователь; требования законодательства РФ.

## 6. Согласие и его отзыв
Регистрируясь на сайте, Пользователь даёт согласие на обработку своих персональных данных на условиях настоящей Политики. Согласие может быть отозвано направлением обращения на {{email}}; в этом случае Оператор прекращает обработку и удаляет данные, если иное не предусмотрено законодательством.

## 7. Хранение и защита
Персональные данные хранятся не дольше, чем требуется для целей обработки или сроков, установленных законодательством РФ. Оператор принимает необходимые правовые, организационные и технические меры для защиты данных от неправомерного доступа.

## 8. Права Пользователя
Пользователь вправе получать сведения об обработке своих данных, требовать их уточнения, блокирования или удаления, а также отозвать согласие. Обращения направляются на {{email}}.

## 9. Изменения Политики
Оператор вправе изменять настоящую Политику. Актуальная редакция размещается на данной странице."""


def _get(db: Session, key: str, default: str = "") -> str:
    row = db.get(ShopSettings, key)
    return row.value if row and row.value else default


def get_privacy(db: Session) -> dict:
    """Текущая политика: тело, дата редакции и реквизиты оператора.

    Структуру разделяют публичный эндпоинт витрины и админка (редактор + превью).
    """
    return {
        "body": _get(db, "privacy_body", DEFAULT_PRIVACY_BODY),
        "revision": _get(db, "privacy_revision", ""),
        "operator": {field: _get(db, key) for field, key in OPERATOR_KEYS.items()},
    }
