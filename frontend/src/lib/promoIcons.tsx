export const PROMO_ICON_NAMES = Object.keys(PATHS);

/** Есть ли такая иконка в наборе (значение из БД могло устареть). */
export function isPromoIconName(name: string): boolean {
  return Object.hasOwn(PATHS, name);
}

/**
 * Одна иконка набора. Рисуется штрихом `currentColor` — цвет задаёт родитель, поэтому
 * на бейдже она всегда белая и одностилевая, чем бы ни был фон.
 */
export default function PromoLucideIcon({ name, className, ...props }: { name: string } & SVGProps<SVGSVGElement>) {
  // Имя приходит из БД и может отстать от набора (иконку переименовали/убрали) — тогда лучше
  // нейтральный ярлык, чем пустой цветной кружок на витрине.
  const path = PATHS[name] ?? PATHS.tag;
  // Надпись занимает почти весь круг — иначе слово из трёх букв не прочитать.
  const cls = [className, PROMO_TEXT_ICONS.has(name) && "pcard__promo__glyph--text"]
    .filter(Boolean).join(" ") || undefined;
  return (
    <svg
      className={cls}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {path}
    </svg>
  );
}
